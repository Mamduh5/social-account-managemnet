import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,renameSync,rmSync,statSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import express from 'express';
import fs from 'node:fs';

test('watch visibility is source-scoped, persisted, reversible and never modifies files or imported masters',async()=>{
  const base=mkdtempSync(path.join(tmpdir(),'scc-watch-fixture-'));
  const data=path.join(base,'scc'),dirA=path.join(base,'source-a'),dirB=path.join(base,'source-b');
  mkdirSync(data);mkdirSync(dirA);mkdirSync(dirB);
  const fileA=path.join(dirA,'same.mp4'),fileB=path.join(dirB,'same.mp4');
  writeFileSync(fileA,'fixture one');writeFileSync(fileB,'fixture two');
  process.env.SCC_DATA_DIR=data;
  const {db,uploadsDir}=await import('../server/src/db/database.js');
  const {initializeDatabase}=await import('../server/src/db/schema.js');
  const {pipelineService}=await import('../server/src/services/pipeline.service.js');
  const {localAccess}=await import('../server/src/local-access.js');
  const {testDataMetadataRouter}=await import('../server/src/routes/test-data-metadata.routes.js');
  initializeDatabase();
  const imported=path.join(uploadsDir,'imported.mp4');writeFileSync(imported,'preserved SCC master');
  const observed=statSync(fileA);
  const metadata=JSON.stringify({sha256:'a'.repeat(64),sourcePath:fileA,sourceSize:observed.size,sourceMtimeMs:observed.mtimeMs});
  db.prepare("INSERT INTO videos(id,title,source_type,original_filename,file_path,metadata_json) VALUES ('imported','Same','manual_upload','same.mp4',?,?)").run(imported,metadata);
  pipelineService.setWatchDirectory(dirA);
  const app=express();app.use(localAccess);app.use(express.json());app.use('/api/test-data-metadata',testDataMetadataRouter);
  const server=await new Promise<ReturnType<typeof app.listen>>(resolve=>{const listener=app.listen(0,'127.0.0.1',()=>resolve(listener));});
  let closed=false;
  try {
    const address=server.address();assert.ok(address&&typeof address!=='string');
    const origin=`http://127.0.0.1:${address.port}`,baseUrl=origin+'/api/test-data-metadata';
    const post=(body:unknown,requestOrigin=origin)=>fetch(baseUrl+'/watch-hidden',{method:'POST',headers:{origin:requestOrigin,'content-type':'application/json'},body:JSON.stringify(body)});
    const get=async(pathname:string)=>{const response=await fetch(baseUrl+pathname);assert.equal(response.status,200);return await response.json() as any;};
    db.exec('ALTER TABLE videos RENAME TO videos_temporarily_unavailable');
    assert.throws(()=>pipelineService.scanWatchDirectory(),/import-reference inspection is unavailable/);
    assert.equal((await fetch(baseUrl+'/watch-files')).status,503,'a database read failure must not become a false no-import match');
    db.exec('ALTER TABLE videos_temporarily_unavailable RENAME TO videos');
    const first=await get('/watch-files?visibility=all');
    assert.equal(first.sourceAvailable,true);assert.equal(first.items.length,1);
    const itemA=first.items[0];assert.equal(itemA.visibilitySupported,true);assert.match(itemA.fileId,/^[a-f0-9]{64}$/);
    assert.equal(itemA.isImported,true);assert.equal(itemA.importedVideoId,'imported');
    assert.equal((await post({fileId:itemA.fileId,sourceFingerprint:itemA.sourceFingerprint,hidden:true},'http://localhost:5180')).status,403);
    assert.equal((await post({fileId:itemA.fileId,sourceFingerprint:itemA.sourceFingerprint,hidden:true})).status,200);
    assert.deepEqual(pipelineService.scanWatchDirectory(),[]);
    assert.equal((await get('/watch-files?visibility=hidden')).items[0].fileId,itemA.fileId);
    assert.equal((await get('/watch-hidden')).items[0].present,true);
    const saved=db.prepare("SELECT key,value FROM app_settings WHERE key LIKE 'cleanup:watch-hidden:%'").get() as {key:string;value:string};
    db.prepare('UPDATE app_settings SET value=? WHERE key=?').run('{broken',saved.key);
    assert.throws(()=>pipelineService.scanWatchDirectory(),'corrupt visibility metadata cannot return a partial visible list');
    assert.equal((await fetch(baseUrl+'/watch-files')).status,503);
    db.prepare('UPDATE app_settings SET value=? WHERE key=?').run(saved.value,saved.key);
    const originalRealpath=fs.realpathSync;
    try {
      fs.realpathSync=((target:any,...args:any[])=>{
        if(typeof target==='string'&&path.resolve(target)===path.resolve(fileA)) throw new Error('synthetic identity failure');
        return (originalRealpath as any)(target,...args);
      }) as typeof fs.realpathSync;
      const ambiguous=await get('/watch-files?visibility=all');
      assert.equal(ambiguous.scanIncomplete,true);
      assert.equal(ambiguous.items[0].visibilitySupported,false);
      assert.equal((await get('/watch-files?visibility=visible')).items.length,0);
      assert.equal(pipelineService.scanWatchDirectory().length,0,'unknown identity is not reintroduced into normal discovery');
      assert.equal((await get('/watch-hidden')).items[0].present,null,'uncertain identity is not presented as definitely missing');
    } finally {fs.realpathSync=originalRealpath;}
    assert.equal((await post({fileId:itemA.fileId,sourceFingerprint:itemA.sourceFingerprint,hidden:false})).status,200);
    assert.equal(pipelineService.scanWatchDirectory()[0].fileId,itemA.fileId,'restore makes the unchanged source discoverable');
    assert.equal((await post({fileId:itemA.fileId,sourceFingerprint:itemA.sourceFingerprint,hidden:true})).status,200);
    assert.equal(readFileSync(fileA,'utf8'),'fixture one');
    assert.equal(readFileSync(imported,'utf8'),'preserved SCC master');
    assert.ok(db.prepare("SELECT 1 FROM videos WHERE id='imported'").get());
    pipelineService.setWatchDirectory(dirB);
    const itemB=(await get('/watch-files?visibility=all')).items[0];
    assert.equal(itemB.filename,itemA.filename);
    assert.notEqual(itemB.sourceFingerprint,itemA.sourceFingerprint);
    assert.notEqual(itemB.fileId,itemA.fileId);
    assert.equal(itemB.hidden,false,'same basename at a different source remains visible');
    assert.equal((await post({fileId:itemA.fileId,sourceFingerprint:itemA.sourceFingerprint,hidden:true})).status,409);
    assert.equal((await get('/watch-hidden')).items.find((item:any)=>item.fileId===itemA.fileId).present,null);
    pipelineService.setWatchDirectory(dirA);
    const oldPath=path.join(base,'original-kept.mp4');renameSync(fileA,oldPath);writeFileSync(fileA,'replacement has different bytes');
    const replacement=(await get('/watch-files?visibility=all')).items[0];
    assert.notEqual(replacement.fileId,itemA.fileId);
    assert.equal(replacement.hidden,false,'a replacement at the same path is not silently hidden');
    assert.equal((await post({fileId:itemA.fileId,sourceFingerprint:itemA.sourceFingerprint,hidden:true})).status,409);
    assert.equal((await get('/watch-hidden')).items.find((item:any)=>item.fileId===itemA.fileId).present,false);
    assert.equal((await post({fileId:itemA.fileId,sourceFingerprint:itemA.sourceFingerprint,hidden:false})).status,200);
    assert.equal(readFileSync(oldPath,'utf8'),'fixture one');assert.equal(readFileSync(fileA,'utf8'),'replacement has different bytes');
    assert.equal((await post({fileId:replacement.fileId,sourceFingerprint:replacement.sourceFingerprint,hidden:true})).status,200);
    await new Promise<void>((resolve,reject)=>server.close(e=>e?reject(e):resolve()));db.close();closed=true;
    const script=`import('./server/src/services/pipeline.service.ts').then(m=>{const s=m.pipelineService??m.default?.pipelineService;const files=s.scanWatchDirectory();const all=s.scanWatchDirectory({includeHidden:true});console.log(JSON.stringify({visible:files.length,hidden:all.filter(x=>x.hidden).length}));});`;
    const restarted=spawnSync(process.execPath,['--import','tsx','-e',script],{cwd:path.resolve(__dirname,'..'),env:{...process.env,SCC_DATA_DIR:data},encoding:'utf8'});
    assert.equal(restarted.status,0,restarted.stderr);
    assert.deepEqual(JSON.parse(restarted.stdout.trim()),{visible:0,hidden:1},'exclusion survives a fresh application process');
    assert.equal(readFileSync(fileA,'utf8'),'replacement has different bytes');
    assert.equal(readFileSync(fileB,'utf8'),'fixture two');assert.equal(readFileSync(imported,'utf8'),'preserved SCC master');
  } finally {if(!closed){await new Promise<void>((resolve,reject)=>server.close(e=>e?reject(e):resolve()));db.close();}rmSync(base,{recursive:true,force:true,maxRetries:10,retryDelay:25});}
});
