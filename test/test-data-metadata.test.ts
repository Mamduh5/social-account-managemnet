import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import express from 'express';
import Database from 'better-sqlite3';

test('owner markings and pipeline exclusions persist independently of names and filter discovery',async()=>{
  const directory=mkdtempSync(path.join(tmpdir(),'scc-owner-markings-'));
  process.env.SCC_DATA_DIR=directory;
  const {db,dbPath}=await import('../server/src/db/database.js');
  const {initializeDatabase}=await import('../server/src/db/schema.js');
  const {localAccess}=await import('../server/src/local-access.js');
  const {testDataMetadataRouter}=await import('../server/src/routes/test-data-metadata.routes.js');
  const {pipelineService}=await import('../server/src/services/pipeline.service.js');
  const {getOwnerClassification,getPipelineSourceFingerprint,isPipelineHidden}=await import('../server/src/services/test-data-metadata.service.js');
  initializeDatabase();
  db.prepare("INSERT INTO categories(id,name,slug) VALUES ('fixture-cat','Fixture','fixture')").run();
  const app=express(); app.use(localAccess); app.use(express.json()); app.use('/api/test-data-metadata',testDataMetadataRouter);
  const server=await new Promise<ReturnType<typeof app.listen>>(resolve=>{const l=app.listen(0,'127.0.0.1',()=>resolve(l));});
  const originalFetch=globalThis.fetch;
  try {
    const address=server.address(); assert.ok(address && typeof address!=='string');
    const origin=`http://127.0.0.1:${address.port}`,base=origin+'/api/test-data-metadata';
    const post=(route:string,body:unknown,requestOrigin=origin)=>originalFetch(base+route,{method:'POST',headers:{'content-type':'application/json',origin:requestOrigin},body:JSON.stringify(body)});
    assert.equal((await post('/classify',{type:'category',id:'fixture-cat',classification:'keep'},'http://localhost:5180')).status,403);
    assert.equal((await post('/classify',{type:'category',id:'missing',classification:'test'})).status,404);
    assert.equal((await post('/classify',{type:'category',id:'fixture-cat',classification:'keep'})).status,200);
    assert.equal(getOwnerClassification(db,'category','fixture-cat'),'owner_marked_keep');
    assert.equal((await post('/classify',{type:'category',id:'fixture-cat',classification:'test'})).status,409);
    assert.equal(getOwnerClassification(db,'category','fixture-cat'),'owner_marked_keep');
    assert.equal((await post('/classify',{type:'category',id:'fixture-cat',classification:'clear'})).status,200);
    assert.equal((await post('/classify',{type:'category',id:'fixture-cat',classification:'test'})).status,200);
    assert.equal(getOwnerClassification(db,'category','fixture-cat'),'owner_marked_test');
    assert.equal((await post('/classify',{type:'category',id:'fixture-cat',classification:'clear'})).status,200);
    assert.equal(getOwnerClassification(db,'category','fixture-cat'),'unknown');
    const sourceA=getPipelineSourceFingerprint(db);
    assert.equal((await post('/pipeline-hidden',{jobId:'job-a',hidden:true,sourceFingerprint:sourceA})).status,200);
    const hiddenList=await (await originalFetch(base+'/pipeline-hidden?limit=1')).json() as any;
    assert.deepEqual(hiddenList.items,[{jobId:'job-a',sourceFingerprint:sourceA,legacy:false,currentSource:true,ownerClassification:'unknown'}]);
    assert.equal((await post('/classify',{type:'pipeline_job',id:'job-a',classification:'keep',sourceFingerprint:sourceA})).status,200);
    assert.equal((await post('/classify',{type:'pipeline_job',id:'job-a',classification:'test',sourceFingerprint:sourceA})).status,409);
    assert.equal(isPipelineHidden(db,'job-a'),true);
    const projects=[{id:'job-a',title:'Identical title',status:'completed',video_url:'/a.mp4'},{id:'job-b',title:'Identical title',status:'completed',video_url:'/b.mp4'}];
    globalThis.fetch=(async()=>new Response(JSON.stringify({api_version:'scene-video-library.v1',projects,page:{has_more:false,next_cursor:null}}))) as typeof fetch;
    const normal=await pipelineService.queryPipelineJobs({limit:20});
    assert.deepEqual(normal.jobs.map(j=>j.jobId),['job-b']);
    const inspection=await pipelineService.queryPipelineJobs({limit:20,includeHidden:true});
    assert.deepEqual(inspection.jobs.map(j=>[j.jobId,j.hidden]),[['job-a',true],['job-b',false]]);
    assert.equal(inspection.jobs[0].ownerClassification,'owner_marked_keep');
    globalThis.fetch=(async(input:RequestInfo|URL)=>{
      const url=new URL(String(input));
      const second=url.searchParams.get('cursor')==='next';
      return new Response(JSON.stringify({api_version:'scene-video-library.v1',projects:[projects[second?1:0]],page:{has_more:!second,next_cursor:second?null:'next'}}));
    }) as typeof fetch;
    const firstPage=await pipelineService.queryPipelineJobs({limit:1});
    assert.equal(firstPage.jobs.length,0);
    assert.equal(firstPage.page.hasMore,true,'a hidden first page does not hide later results');
    assert.equal(firstPage.page.nextCursor,'next');
    assert.equal(firstPage.totalMatched,undefined,'no complete visible count is invented');
    const nextPage=await pipelineService.queryPipelineJobs({limit:1,cursor:firstPage.page.nextCursor});
    assert.deepEqual(nextPage.jobs.map(j=>j.jobId),['job-b']);
    globalThis.fetch=(async(input:RequestInfo|URL)=>String(input).includes('/scene-video-library')
      ? new Response('',{status:404})
      : new Response(JSON.stringify({projects,has_more:false}))) as typeof fetch;
    const legacy=await pipelineService.queryPipelineJobs({limit:20});
    assert.equal(legacy.sourceContract,'legacy_jobs');
    assert.deepEqual(legacy.jobs.map(j=>j.jobId),['job-b']);
    globalThis.fetch=originalFetch;
    assert.equal((await post('/pipeline-hidden',{jobId:'job-a',hidden:false,sourceFingerprint:sourceA})).status,200);
    assert.equal(isPipelineHidden(db,'job-a'),false);
    assert.equal((await post('/pipeline-hidden',{jobId:'job-a',hidden:true,sourceFingerprint:sourceA})).status,200);
    db.prepare("INSERT INTO app_settings(key,value) VALUES ('pipeline_api_url','http://localhost:9090') ON CONFLICT(key) DO UPDATE SET value=excluded.value").run();
    const sourceB=getPipelineSourceFingerprint(db);
    assert.notEqual(sourceA,sourceB);
    assert.equal(isPipelineHidden(db,'job-a'),false,'same ID at another upstream is not hidden');
    assert.equal(getOwnerClassification(db,'pipeline_job','job-a'),'unknown','same ID at another upstream is not marked');
    assert.equal((await post('/pipeline-hidden',{jobId:'job-a',hidden:true,sourceFingerprint:sourceA})).status,409);
    assert.equal((await post('/classify',{type:'pipeline_job',id:'job-a',classification:'test',sourceFingerprint:sourceA})).status,409);
    const oldSourceList=await (await originalFetch(base+'/pipeline-hidden')).json() as any;
    assert.equal(oldSourceList.items[0].currentSource,false);
    assert.equal((await post('/pipeline-hidden',{jobId:'job-a',hidden:false,sourceFingerprint:sourceA})).status,200,'old-source exclusion can be restored explicitly');
    assert.equal((await post('/pipeline-hidden',{jobId:'job-a',hidden:true,sourceFingerprint:sourceB})).status,200);
    const legacyKey='cleanup:pipeline-hidden:'+Buffer.from('legacy-id').toString('base64url');
    db.prepare("INSERT INTO app_settings(key,value) VALUES (?,'hidden')").run(legacyKey);
    assert.equal(isPipelineHidden(db,'legacy-id'),true,'unscoped legacy exclusion remains effective');
    const legacyList=await (await originalFetch(base+'/pipeline-hidden')).json() as any;
    assert.equal(legacyList.items.find((item:any)=>item.jobId==='legacy-id').legacy,true);
    assert.equal((await post('/pipeline-hidden',{jobId:'legacy-id',hidden:false,sourceFingerprint:null,legacy:true})).status,200);
    assert.equal(isPipelineHidden(db,'legacy-id'),false,'legacy exclusion can be restored');
    const legacyClassification='cleanup:classification:'+Buffer.from(JSON.stringify(['pipeline_job','legacy-mark'])).toString('base64url');
    db.prepare("INSERT INTO app_settings(key,value) VALUES (?,'owner_marked_keep')").run(legacyClassification);
    assert.equal(getOwnerClassification(db,'pipeline_job','legacy-mark'),'owner_marked_keep');
    assert.equal((await post('/classify',{type:'pipeline_job',id:'legacy-mark',classification:'clear',sourceFingerprint:sourceB})).status,200);
    assert.equal(getOwnerClassification(db,'pipeline_job','legacy-mark'),'unknown');
    db.prepare("UPDATE app_settings SET value='http://localhost:7070' WHERE key='pipeline_api_url'").run();
    assert.equal(getOwnerClassification(db,'pipeline_job','legacy-mark'),'owner_marked_keep','clearing one source preserves the legacy mark for other sources');
    db.prepare("UPDATE app_settings SET value='http://localhost:9090' WHERE key='pipeline_api_url'").run();
    assert.equal(getOwnerClassification(db,'pipeline_job','legacy-mark'),'unknown');
    assert.equal((await post('/pipeline-hidden',{jobId:'job-b',hidden:true,sourceFingerprint:sourceB})).status,200);
    const hiddenFirst=await (await originalFetch(base+'/pipeline-hidden?limit=1&offset=0')).json() as any;
    const hiddenSecond=await (await originalFetch(base+'/pipeline-hidden?limit=1&offset=1')).json() as any;
    assert.equal(hiddenFirst.hasMore,true); assert.equal(hiddenSecond.hasMore,false);
    assert.deepEqual(new Set([hiddenFirst.items[0].jobId,hiddenSecond.items[0].jobId]),new Set(['job-a','job-b']));
    assert.equal((await post('/pipeline-hidden',{jobId:'job-b',hidden:false,sourceFingerprint:sourceB})).status,200);
    assert.equal((await post('/classify',{type:'category',id:'fixture-cat',classification:'keep'})).status,200);
  } finally {
    globalThis.fetch=originalFetch;
    await new Promise<void>((resolve,reject)=>server.close(e=>e?reject(e):resolve()));
    db.close();
  }
  const reopened=new Database(dbPath,{readonly:true});
  try {
    assert.equal(getOwnerClassification(reopened,'category','fixture-cat'),'owner_marked_keep');
    assert.equal(isPipelineHidden(reopened,'job-a'),true);
    assert.equal(isPipelineHidden(reopened,'job-b'),false);
    assert.deepEqual(reopened.pragma('foreign_key_check'),[]);
  } finally {reopened.close();rmSync(directory,{recursive:true,force:true,maxRetries:10,retryDelay:25});}
});
