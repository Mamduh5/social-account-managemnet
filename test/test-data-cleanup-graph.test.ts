import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';

test('selected local video graph and terminal simulator posts delete only exact reviewed rows',async()=>{
  const directory=mkdtempSync(path.join(tmpdir(),'scc-cleanup-graph-'));
  process.env.SCC_DATA_DIR=directory;
  const {db,uploadsDir,rendersDir}=await import('../server/src/db/database.js');
  const {initializeDatabase}=await import('../server/src/db/schema.js');
  const {deletionSnapshot,commitDeletion,inspectDeletion}=await import('../server/src/repositories/test-data-deletion.repo.js');
  const {setOwnerClassification}=await import('../server/src/services/test-data-metadata.service.js');
  initializeDatabase();
  const videoPath=path.join(uploadsDir,'fixture-master.mp4'),renderPath=path.join(rendersDir,'fixture-render.mp4');
  writeFileSync(videoPath,'synthetic master'); writeFileSync(renderPath,'synthetic render');
  db.prepare("INSERT INTO accounts(id,name,handle,platform,account_type,status,connector_mode,is_demo,connection_status) VALUES ('sim','Simulator','sim','tiktok','personal','failed','simulator',1,'registered'),('real','Real','real','facebook','page','connected','official_api',0,'connected')").run();
  db.prepare("INSERT INTO videos(id,title,source_type,original_filename,file_path) VALUES (?,?,?,?,?)").run('v1','Same title','manual_upload','fixture-master.mp4',videoPath);
  db.prepare("INSERT INTO videos(id,title,source_type,original_filename,file_path) VALUES (?,?,?,?,?)").run('v2','Same title','manual_upload','other.mp4',path.join(uploadsDir,'other.mp4'));
  db.prepare("INSERT INTO branded_videos(id,video_id,preset_name,movement_preset,watermark_text,file_path) VALUES ('b1','v1','Fixture','static_corner','fixture',?)").run(renderPath);
  db.prepare("INSERT INTO publishing_posts(id,video_id,title,status,selected_variant_id) VALUES ('p1','v1','Duplicate campaign title','failed','b1'),('p2','v2','Duplicate campaign title','failed',NULL)").run();
  db.prepare("INSERT INTO publishing_destinations(id,post_id,account_id,caption,status,retry_count,selected_variant_id,branded_video_path) VALUES ('d1','p1','sim','fixture','failed',3,'b1',?),('d2','p2','sim','fixture','failed',1,NULL,NULL)").run(renderPath);
  db.prepare("INSERT INTO publishing_destinations(id,post_id,account_id,caption,status,retry_count) VALUES ('d1b','p1','sim','fixture','failed',2)").run();
  try {
    const insertVariant=db.prepare("INSERT INTO branded_videos(id,video_id,preset_name,movement_preset,watermark_text,file_path) VALUES (?,'v2','Fixture','static_corner','fixture',?)");
    db.transaction(()=>{for(let i=0;i<51;i++)insertVariant.run('extra-'+i,path.join(rendersDir,'extra-'+i+'.mp4'));})();
    const incomplete=deletionSnapshot(db,[{type:'video',id:'v2'}]).records[0];
    assert.equal(incomplete.eligible,false);
    assert.match(incomplete.reason,/incomplete/i,'truncated relationship evidence blocks deletion');
    db.prepare("DELETE FROM branded_videos WHERE video_id='v2'").run();
    const items=[{type:'video',id:'v1'},{type:'branded_video',id:'b1'},{type:'publishing_post',id:'p1'}];
    assert.equal(inspectDeletion(db,{type:'video',id:'v1'}).impact.eligible,false);
    assert.equal(inspectDeletion(db,{type:'video',id:'v1'},true).impact.selectable,true);
    assert.equal(inspectDeletion(db,{type:'publishing_post',id:'p1'},true).impact.selectable,true);
    const single=deletionSnapshot(db,[{type:'video',id:'v1'}]);
    assert.equal(single.records[0].eligible,false,'unselected related records block the master');
    db.prepare("UPDATE publishing_destinations SET status='uploading' WHERE id='d1'").run();
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'active job blocks graph');
    db.prepare("UPDATE publishing_destinations SET status='failed',remote_post_id='remote-uncertain' WHERE id='d1'").run();
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'remote identifier blocks graph');
    db.prepare("UPDATE publishing_destinations SET remote_post_id=NULL,submission_state='created' WHERE id='d1'").run();
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'submission intent blocks graph');
    db.prepare("UPDATE publishing_destinations SET submission_state=NULL,account_id='real' WHERE id='d1'").run();
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'real account blocks graph');
    db.prepare("UPDATE publishing_destinations SET account_id='sim' WHERE id='d1'").run();
    db.prepare("INSERT INTO account_identities(platform,identity_key,account_id) VALUES ('tiktok','legacy-external-identity','sim')").run();
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'external identity alias blocks graph');
    db.prepare("DELETE FROM account_identities WHERE account_id='sim'").run();
    db.prepare("INSERT INTO oauth_sessions(state_hash,browser_hash,account_id,revision,expires_at) VALUES ('state','browser','sim',1,9999999999999)").run();
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'OAuth session blocks graph');
    db.prepare("DELETE FROM oauth_sessions WHERE account_id='sim'").run();
    db.prepare("UPDATE accounts SET granted_scopes_json='[\"video.list\"]' WHERE id='sim'").run();
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'external grant blocks graph');
    db.prepare("UPDATE accounts SET granted_scopes_json='[]' WHERE id='sim'").run();
    setOwnerClassification(db,'publishing_destination','d1','owner_marked_keep');
    assert.equal(deletionSnapshot(db,items).records.some(row=>!row.eligible),true,'owner Keep on implicit child blocks graph');
    setOwnerClassification(db,'publishing_destination','d1','unknown');
    const preview=deletionSnapshot(db,items);
    assert.equal(preview.records.every(row=>row.eligible),true,JSON.stringify(preview.records));
    assert.deepEqual(preview.records.flatMap(row=>row.rows).map(row=>row.table+':'+row.id).sort(),['branded_videos:b1','publishing_destinations:d1','publishing_destinations:d1b','publishing_posts:p1','videos:v1'].sort());
    setOwnerClassification(db,'branded_video','b1','owner_marked_keep');
    assert.throws(()=>commitDeletion(db,items,preview.fingerprint,'audit-stale'),/STALE_PREVIEW/);
    assert.ok(db.prepare("SELECT 1 FROM videos WHERE id='v1'").get());
    setOwnerClassification(db,'branded_video','b1','unknown');
    const refreshed=deletionSnapshot(db,items);
    const result=commitDeletion(db,items,refreshed.fingerprint,'audit-cleanup');
    assert.equal(result.rowCount,5); assert.equal(result.count,3);
    assert.throws(()=>commitDeletion(db,items,refreshed.fingerprint,'audit-replay'),/STALE_PREVIEW/);
    assert.equal(readFileSync(videoPath,'utf8'),'synthetic master');
    assert.equal(readFileSync(renderPath,'utf8'),'synthetic render');
    assert.ok(db.prepare("SELECT 1 FROM publishing_posts WHERE id='p2'").get());
    assert.ok(db.prepare("SELECT 1 FROM publishing_destinations WHERE id='d2'").get());
    assert.ok(db.prepare("SELECT 1 FROM videos WHERE id='v2'").get());
    assert.ok(db.prepare("SELECT 1 FROM accounts WHERE id='sim'").get());
    assert.deepEqual(db.pragma('foreign_key_check'),[]);
  } finally {db.close();rmSync(directory,{recursive:true,force:true,maxRetries:10,retryDelay:25});}
});
